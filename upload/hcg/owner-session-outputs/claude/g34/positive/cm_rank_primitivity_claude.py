"""Claude: Hodge-torus rank versus primitivity for CM abelian sixfolds of Weil type for K = Q(sqrt(-3)).

Setting (standard CM theory; the reduction is in the accompanying note, section 3):
  E = E+ . K is a CM field of degree 12 containing K (always E = E+ K), Gal(E~/Q) = G+ x <iota>, with
  G+ = Gal(E+~/Q) a transitive subgroup of S6 acting on the six embeddings of E+, iota = complex conjugation (central).
  A CM type Phi of E whose K-signature is (3,3) <-> a balanced sign vector s in {+1,-1}^6, sum s = 0.
  (s_k = +1 iff Phi contains the embedding over tau_K lying above the k-th embedding of E+.)
  Hodge classes on A^r <-> exponent vectors with antisymmetric part a in Z^6 orthogonal to span{g.s : g in G+}
  (iota acts by -1). Hence
     rank Hg(A) = dim_Q span{g.s : g in G+}  (<= 5, since every g.s is orthogonal to (1,...,1)),
  and the Hodge ring of every power is generated by divisor classes and E-transported Weil classes
  iff this rank is 5 (then the orthogonal complement is Q.(1,...,1)).
  Primitivity (A simple): Phi is primitive iff its right stabilizer in G+ x <iota> is Gal(E~/E) = H+ x 1,
  H+ = point stabilizer. With f(g) = s(g(x0)): (gamma, eta) stabilizes iff f(g gamma) = eta f(g) for all g.
Input: transitive6.json exported by gap/transitive6_export.g (GAP TransitiveGroups library).
Usage: python3 -I cm_rank_primitivity_claude.py transitive6.json
"""
import sys, json, itertools
from fractions import Fraction


def rank_q(rows):
    m = [[Fraction(x) for x in r] for r in rows]
    rk, col, ncol = 0, 0, len(m[0]) if m else 0
    while rk < len(m) and col < ncol:
        piv = next((i for i in range(rk, len(m)) if m[i][col] != 0), None)
        if piv is None:
            col += 1
            continue
        m[rk], m[piv] = m[piv], m[rk]
        for i in range(len(m)):
            if i != rk and m[i][col] != 0:
                q = m[i][col] / m[rk][col]
                m[i] = [a - q * b for a, b in zip(m[i], m[rk])]
        rk += 1
        col += 1
    return rk


def act(g, s):                      # (g.s)(x) = s(g^-1 x); same span as s o g
    out = [0] * 6
    for x in range(6):
        out[g[x]] = s[x]
    return tuple(out)


def compose(g, h):                  # (g h)(x) = g(h(x))
    return tuple(g[h[x]] for x in range(6))


EXC = {}


def main(path):
    data = json.load(open(path))
    balanced = [s for s in itertools.product((1, -1), repeat=6) if sum(s) == 0]
    assert len(balanced) == 20
    # sublemma checked by ChatGPT: dot products of balanced vectors
    dots = sorted({sum(a * b for a, b in zip(s, t)) for s in balanced for t in balanced})
    print('balanced vectors:', len(balanced), ' ordered pairs:', len(balanced) ** 2, ' dot products:', dots)
    x0 = 0
    findings = []
    for e in data:
        G = [tuple(i - 1 for i in g) for g in e['els']]
        Hplus = [g for g in G if g[x0] == x0]
        table = {}
        for s in balanced:
            orbit = {act(g, s) for g in G}
            rk = rank_q(list(orbit))
            f = {g: s[g[x0]] for g in G}
            stab = [(gam, eta) for gam in G for eta in (1, -1)
                    if all(f[compose(g, gam)] == eta * f[g] for g in G)]
            prim = len(stab) == len(Hplus) and all(eta == 1 and gam[x0] == x0 for gam, eta in stab)
            # left stabilizer in G+ x <iota> (what a cyclic model computes)
            lstab = sum(1 for g in G for eta in (1, -1) if act(g, s) == tuple(eta * v for v in s))
            table.setdefault((rk, prim), []).append((s, lstab))
            if prim and rk < 5:
                findings.append((e['k'], e['name'], s, rk))
            # cross-check by enumeration: exceptional exponent vectors a in [-r, r]^6, a not constant,
            # orthogonal to the orbit (Hodge classes on A^r not generated by divisor and Weil classes)
            exc = None
            for r in (1, 2, 3):
                for a in itertools.product(range(-r, r + 1), repeat=6):
                    if len(set(a)) > 1 and all(sum(x * y for x, y in zip(a, o)) == 0 for o in orbit):
                        exc = r
                        break
                if exc:
                    break
            assert (rk == 5) == (exc is None), (e['k'], s, rk, exc)
            EXC.setdefault((e['k'], rk), set()).add(exc)
        summary = ', '.join(f"rank {rk} {'primitive' if p else 'imprimitive'}: {len(v)}"
                            for (rk, p), v in sorted(table.items(), key=lambda t: (-t[0][0], not t[0][1])))
        # left stabilizer of s in G+ x <iota> is trivial iff lstab == 1
        nprim_left_nontriv = sum(1 for (rk, p), v in table.items() if p for (s, l) in v if l > 1)
        nimprim_left_triv = sum(1 for (rk, p), v in table.items() if not p for (s, l) in v if l == 1)
        print(f"6T{e['k']:<2} |G+|={e['order']:<4} {e['name']:<42} {summary}"
              f"   [primitive with nontrivial left stabilizer: {nprim_left_nontriv}; "
              f"imprimitive with trivial left stabilizer: {nimprim_left_triv}]")
    print()
    print('enumeration cross-check (exceptional exponent vectors, |a_k| <= r <= 3): rank 5 <=> none, for all',
          16 * 20, 'pairs (group, type); smallest r with an exceptional class, by (group, rank):')
    print('  ', {f'6T{k} rank {rk}': sorted(v) for (k, rk), v in sorted(EXC.items()) if rk < 5})
    print('primitive balanced types with rank < 5:', len(findings))
    for k, name, s, rk in findings:
        print(f'  6T{k} {name}: s = {s}, rank {rk}')
    return findings


if __name__ == '__main__':
    main(sys.argv[1])
