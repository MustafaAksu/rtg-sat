#!/usr/bin/env python3
"""G34-A (Claude, independent of Severn's code and tuple).
Construct G34 = Aut_E(K12)-reflection group from the 756 minimal vectors of the Coxeter-Todd lattice
in its Eisenstein form K12 = {x in E^6 : x_i ≡ x_j (mod theta), sum x_i ≡ 0 (mod 3)}, E = Z[w], w^2+w+1=0,
theta = w - w^2 = 1+2w (Conway-Sloane SPLAG ch.4 §9 description). Reflections of order 2 in minimal vectors v:
r_v(x) = x - 2 h(x,v)/h(v,v) v,  h(x,y) = sum x_i conj(y_i).  Exact arithmetic only."""
import itertools, json, hashlib, sys, random
from fractions import Fraction as Fr
from sympy.combinatorics import Permutation, PermutationGroup

# ---- exact Q(w): (a,b) = a + b w, w^2 = -1 - w
def mul(x,y): a,b=x; c,d=y; return (a*c-b*d, a*d+b*c-b*d)
def add(x,y): return (x[0]+y[0], x[1]+y[1])
def sub(x,y): return (x[0]-y[0], x[1]-y[1])
def conj(x): a,b=x; return (a-b,-b)          # w -> w^2 = -1-w
def norm(x): a,b=x; return a*a-a*b+b*b
def scal(q,x): return (q*x[0], q*x[1])
ZERO=(0,0); ONE=(1,0); W=(0,1); W2=(-1,-1)
UNITS=[(1,0),(-1,0),(0,1),(0,-1),(-1,-1),(1,1)]
THETA=(1,2)
def herm(x,y):
    s=ZERO
    for xi,yi in zip(x,y): s=add(s,mul(xi,conj(yi)))
    return s
def res_theta(x): return (x[0]+x[1])%3          # w ≡ 1 mod theta
def in_K12(x):
    if any(not (Fr(c).denominator==1) for xi in x for c in xi): return False
    x=[(int(a),int(b)) for a,b in x]
    if len({res_theta(xi) for xi in x})!=1: return False
    s=(sum(a for a,_ in x), sum(b for _,b in x))
    return s[0]%3==0 and s[1]%3==0

# ---- minimal vectors (norm 6)
entries=[ZERO]+UNITS+[mul(THETA,u) for u in UNITS]
minv=[]
for x in itertools.product(entries, repeat=6):
    if sum(norm(e) for e in x)!=6: continue
    if in_K12(x): minv.append(tuple(x))
idx={v:i for i,v in enumerate(minv)}
print("minimal vectors:",len(minv))

def reflect(v,x):
    c=herm(x,v)                       # h(v,v)=6, factor 2/6 = 1/3
    c=(Fr(c[0],3),Fr(c[1],3))
    return tuple(sub(xi, mul(c,vi)) for xi,vi in zip(x,v))
lines={}
for v in minv:
    key=min(idx[tuple(mul(u,c) for c in v)] for u in UNITS)
    lines.setdefault(key,v)
reps=[lines[k] for k in sorted(lines)]
print("reflection lines:",len(reps))

def as_perm(v):
    img=[]
    for x in minv:
        y=reflect(v,x)
        y=tuple((int(a),int(b)) for a,b in y) if all(Fr(c).denominator==1 for t in y for c in t) else None
        if y is None or y not in idx: return None
        img.append(idx[y])
    return Permutation(img)
perms=[as_perm(v) for v in reps]
ok_preserve=all(p is not None for p in perms)
ok_inv=all(p is not None and (p*p).is_Identity for p in perms)
print("all reflections preserve the 756 minimal vectors:",ok_preserve," order 2:",ok_inv)

# ---- group generated by all 126 reflections; then find 10 generating ones
G=PermutationGroup(perms)
order=G.order(); print("|G| =",order)
random.seed(34)
gens10=None
for trial in range(200):
    pick=random.sample(range(len(reps)),10)
    if PermutationGroup([perms[i] for i in pick]).order()==order:
        gens10=pick; break
print("10 generating reflections (indices into line list):",gens10)

# ---- centre: scalars -1 and w are in G
def scalar_perm(u): return Permutation([idx[tuple(mul(u,c) for c in x)] for x in minv])
z_m1=G.contains(scalar_perm((-1,0))); z_w=G.contains(scalar_perm(W))
print("-I in G:",z_m1,"  wI in G:",z_w)
# single conjugacy class of reflections: G transitive on the 126 lines
orbit=G.orbit(idx[reps[0]]); print("orbit of a minimal vector under G:",len(orbit))

# ---- irreducibility over K: commutant of the generating reflections (as 6x6 matrices) = K
def mat_of(v):   # matrix of r_v on standard basis, columns = images of e_k (coefficients in Q(w))
    cols=[]
    for k in range(6):
        e=[ZERO]*6; e[k]=ONE
        cols.append(reflect(v,e))
    return [[cols[k][i] for k in range(6)] for i in range(6)]
Ms=[mat_of(reps[i]) for i in gens10]
# commutant: columns = (X M - M X) for X ranging over the 72 Q-basis matrices E_ij*{1,w}
import flint, functools
def mmul(M,N): return [[functools.reduce(add,[mul(M[i][k],N[k][j]) for k in range(6)]) for j in range(6)] for i in range(6)]
cols=[]
for i in range(6):
    for j in range(6):
        for val in (ONE,W):
            X=[[ZERO]*6 for _ in range(6)]; X[i][j]=val
            col=[]
            for M in Ms:
                XM=mmul(X,M); MX=mmul(M,X)
                for a in range(6):
                    for b in range(6):
                        dlt=sub(XM[a][b],MX[a][b]); col+=[flint.fmpq(Fr(dlt[0]).numerator,Fr(dlt[0]).denominator),flint.fmpq(Fr(dlt[1]).numerator,Fr(dlt[1]).denominator)]
            cols.append(col)
A_=flint.fmpq_mat([[cols[c][r] for c in range(72)] for r in range(len(cols[0]))])
comm_dim=72-A_.rank()
print("dim_Q commutant =",comm_dim,"(2 means End = K: irreducible over K)")

# ---- character field: some product of two generators has non-real trace
def trace(M): s=ZERO
nonreal=None   # traces of r_a r_b are always real; use triple products
for a in range(len(Ms)):
    for b in range(a+1,len(Ms)):
        for c in range(b+1,len(Ms)):
            P=mmul(mmul(Ms[a],Ms[b]),Ms[c]); tr=ZERO
            for i in range(6): tr=add(tr,P[i][i])
            if tr[1]!=0: nonreal=(a,b,c,(str(tr[0]),str(tr[1]))); break
        if nonreal: break
    if nonreal: break
print("non-real trace of a triple product (a,b,c,(re,w-coeff)):",nonreal,"| also chi(wI)=6w since wI in G")

# ---- paired Nielsen tuple (s1,s1,...,s10,s10): product one, generates G
tuple20=[g for g in gens10 for _ in (0,1)]
prod=Permutation(list(range(len(minv))))
for i in tuple20: prod=prod*perms[i]
print("20-tuple product is identity:",prod.is_Identity)

# ---- Chevalley-Weil multiplicity and Hodge numbers (independent formula)
d=6; r=20; fixdim=5            # reflection: fixed space dim 5, one eigenvalue -1
m_sigma=(r-2)*d - r*fixdim
hol = -d + r*(1-Fr(1,2))       # sum over non-trivial eigenvalues exp(2 pi i a) of (1-a), a=1/2
print("m_sigma =",m_sigma," Hodge (h10,h01) =",(hol, m_sigma-hol)," Hurwitz dim r-3 =",r-3)

out={"source":"K12 Eisenstein form (Conway-Sloane SPLAG ch.4 §9); reflections in minimal vectors",
     "n_minimal_vectors":len(minv),"n_reflection_lines":len(reps),"group_order":int(order),
     "preserve":ok_preserve,"involutions":ok_inv,"minus_I_in_G":bool(z_m1),"wI_in_G":bool(z_w),
     "orbit_minimal_vectors":len(orbit),"commutant_dim_Q":int(comm_dim),"nonreal_trace":str(nonreal),
     "generating_reflection_roots":[ [list(c) for c in reps[i]] for i in gens10],
     "paired_tuple_root_indices":tuple20,"tuple_product_identity":bool(prod.is_Identity),
     "m_sigma":m_sigma,"hodge":[str(hol),str(m_sigma-hol)],"hurwitz_dim":r-3}
json.dump(out,open("g34_gateA.json","w"),indent=1)
print("sha256(script) =",hashlib.sha256(open(__file__,'rb').read()).hexdigest())
