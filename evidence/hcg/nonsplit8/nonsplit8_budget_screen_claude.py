print(f"{'d':>3} {'eps_max':>7}  shape -> bound / verdict")
for d in range(6,13):
    emax=2*d-11; rows=[]
    rows.append(('monomial (r=1)', None, 'EXCL (Severn v1 Sec.8)'))
