import math
ranks_exceptional={3:['G23(H3,real)','G24','G25','G26','G27'],4:['G28(F4,real)','G29','G30(H4,real)','G31','G32'],
                   5:['G33'],6:['G34','G35(E6,real)'],7:['G36(E7,real)'],8:['G37(E8,real)']}
