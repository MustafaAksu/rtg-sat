"""Claude: arithmetic behind the two-block lemma (non-K-defined blocks, k = 2, d = 2r), stdlib only.
Inputs (all CHECKED earlier): reflection-free, gamma = 0 for the intermediate double cover (two swap points),
Galois swap of the two Lambda-isotypic blocks => every block-preserving branch element has c = 2*rho (rho on each block),
swap elements c = r + rank(1-P_i), N >= 19, sum c = 2d+8 = 4r+8.
Excess E = sum_i (c_si - r) + 2*sum(rho_j - 1) + 2*(N-19) <= 2r - 26.
Closing conditions for the inducing datum tau_1 on Y = P^1 (rank r, generated by its local monodromies):
 (a) a reflection exists among the local monodromies (some rho_j = 1): need #block-preserving (>=17) > sum(rho-1) bound;
 (b) finer block systems of W_R(tau_1) with k' >= 2 blocks of rank r' give a Gamma-block system with 2k' blocks of rank r':
     field-free period/budget requires r' >= 6 and r' + 2(2k') >= 17;
 (c) W_R(tau_1) = S_{r+1}: every local monodromy on Y must have scalar part 1, which holds if its rank is
     < r - floor((r+1)/2); max local ranks are rho_max = 1 + floor(E/2) and P_max = E.
     Then psi is unramified on P^1, hence trivial, the character of tau_1 is rational and chi_sigma is rational (contradiction).
 (d) W_R(tau_1) monomial G(m,p,r) (normalizer monomial, r >= 5) or W_R diagonal: sigma monomial, excluded.
"""
for r in range(13,21):
    d=2*r; E=2*r-26
    rho_max=1+E//2; P_max=E; thr=r-(r+1)//2
    a_ok = 17 > E//2
    finer=[(kp,r//kp) for kp in range(2,r+1) if r%kp==0 and r//kp>=2]
    b_bad=[(kp,rp) for kp,rp in finer if rp>=6 and rp+2*(2*kp)>=17]
    c_ok = max(rho_max,P_max) < thr
    verdict='EXCLUDED' if (a_ok and not b_bad and c_ok) else 'OPEN'
    print(f'r={r:2d} d={d:2d} E<={E:2d}  rho_max={rho_max:2d} P_max={P_max:2d} S-threshold={thr:2d} '
          f'reflection-present={a_ok} finer-blocks-surviving={b_bad} S-case-closed={c_ok} -> {verdict}')
# which (k,r) block shapes survive the reflection-free imprimitive budget for 26 <= d <= 41 ?
print('imprimitive shapes (k,r) with r>=6, r+2k>=17, 26<=d<=41:')
for d in range(26,42):
    sh=[(k,d//k) for k in range(2,d) if d%k==0 and d//k>=6 and d//k+2*k>=17]
    if sh: print(f'  d={d}: {sh}')
