def refl(v):
    n = len(v); hv = Z
    for x in v: hv = ad(hv, ml(x, cj(x)))
    c = ml(K(-2), iv(hv))
    return [[ad(ONE if i == j else Z, ml(c, ml(v[i], cj(v[j])))) for j in range(n)] for i in range(n)]
def load_W(path):
    d = json.load(open(path))
    roots = [[K(p, q) for p, q in r] for r in d['roots']]
    s = [refl(v) for v in roots]
    gs = [m for x in s for m in (x, x)]
    curves = [tuple(c['curve']) for c in d['curves']]
    return gs, 6, curves
def g616():
    n = 6; z6 = K(1, 1); mu = [kp(z6, e) for e in range(6)]
    def D(i, e):
        M = eye(n); M[i][i] = mu[e]; return M
    def T(i, j, a):
        M = eye(n); M[i][i] = Z; M[j][j] = Z; M[i][j] = mu[a % 6]; M[j][i] = mu[(-a) % 6]; return M
    def pairs(spec): return [m for (i, j, a) in spec for m in (T(i, j, a), T(i, j, a))]
    base = [(0, 1, 1), (1, 2, 0), (2, 3, 2), (3, 4, 0), (4, 5, 1), (0, 5, 3), (1, 3, 1), (2, 4, 5)]
    return {
        'P1': [D(0, 3), D(0, 1), D(0, 4), D(0, 4)] + pairs(base),
        'P2': [D(3, 3), D(3, 2), D(3, 2), D(3, 5)] + pairs(base),
        'P3': [D(0, 3), D(1, 3), D(1, 3), D(0, 1), D(0, 4), D(0, 4)] + pairs(base[:7]),
        'Q0': [D(0, 1), D(0, 5), D(2, 1), D(2, 5)] + pairs(base),
        'Q2': [D(0, 3), D(0, 3), D(4, 1), D(4, 5)] + pairs(base),
    }
def f20_matrix(k, a, b, conv):
    """omega^k times rho4(x -> a x + b) on the sum-zero part of Q^5, basis e_i - e_4."""
    perm = [(a * x + b) % 5 for x in range(5)]
    P = [[ONE if (perm[c] == r if conv == 0 else perm[r] == c) else Z for c in range(5)] for r in range(5)]
    B = [[ONE if r == c else (K(-1) if r == 4 else Z) for c in range(4)] for r in range(5)]   # columns e_c - e_4
    PB = mm(P, B)                                    # express in basis: coordinate c = entry c (rows 0..3)
    M = [[PB[r][c] for c in range(4)] for r in range(4)]
    s = kp(W, k % 3)
    return [[ml(s, x) for x in r] for r in M]
def load_f20(path):
    out = []
    for line in open(path):
        if not line.startswith('['): continue
        t = ast.literal_eval(line[:line.index('] dim') + 1])
        cls = line[line.index('class') + 6:line.index('t=#')].strip()
        sig = line[line.index('sig') + 4:line.index('class')].strip()
        out.append((t, sig, cls))
    return out

def f20_marking(t):
    for conv in (0, 1):
        for order in (t, t[::-1]):
            gs = [f20_matrix(k, a, b, conv) for k, (a, b) in order]
            if prod(gs, 4) == eye(4): return gs, conv, order is t
    raise AssertionError("no convention gives product one")

# ---------- program checks ----------
def check_dp(gs_pool, n, rnd, trials, label):
    done = 0
    while done < trials:
        N = rnd.randint(4, 9)
        gs = [rnd.choice(gs_pool) for _ in range(N - 1)]
        gs.append(minv(prod(gs, n)))
        M = Marking(gs, n)
        hi, lo, wh, wl = M.dp()
        vals = [M.evaluate(t) for t in all_planar(0, N - 2)]
        assert (max(vals), min(vals)) == (hi, lo), (label, N, hi, lo, max(vals), min(vals))
        assert M.evaluate(wh) == hi and M.evaluate(wl) == lo
        done += 1
    print(f"program check [{label}]: dynamic programme = explicit enumeration on {trials} random product-one markings, N in 4..9: PASS")

