import json, ast, random, sys
from fractions import Fraction as Fr
from functools import lru_cache

# ---------- K = Q(w), w^2 + w + 1 = 0;  element (a, b) = a + b w ----------
Z = (Fr(0), Fr(0)); ONE = (Fr(1), Fr(0)); W = (Fr(0), Fr(1))
def ad(x, y): return (x[0] + y[0], x[1] + y[1])
def sb(x, y): return (x[0] - y[0], x[1] - y[1])
def ml(x, y): return (x[0]*y[0] - x[1]*y[1], x[0]*y[1] + x[1]*y[0] - x[1]*y[1])
def cj(x): return (x[0] - x[1], -x[1])
def nz(x): return x[0] != 0 or x[1] != 0
def iv(x):
    c = cj(x); n = x[0]*x[0] - x[0]*x[1] + x[1]*x[1]; return (c[0]/n, c[1]/n)
def kp(x, e):
    r = ONE
    for _ in range(e): r = ml(r, x)
    return r
def K(p, q=0): return (Fr(p), Fr(q))

def eye(n): return [[ONE if i == j else Z for j in range(n)] for i in range(n)]
def mm(A, B):
    n, m, p = len(A), len(B), len(B[0])
    return [[_dot(A[i], [B[k][j] for k in range(m)]) for j in range(p)] for i in range(n)]
def _dot(r, c):
    s = Z
    for a, b in zip(r, c):
        if nz(a) and nz(b): s = ad(s, ml(a, b))
    return s
def msub(A, B): return [[sb(a, b) for a, b in zip(r, s)] for r, s in zip(A, B)]
def rank(rows):
    M = [r[:] for r in rows]; rk = 0; ncol = len(M[0]) if M else 0
    for c in range(ncol):
        p = next((i for i in range(rk, len(M)) if nz(M[i][c])), None)
        if p is None: continue
        M[rk], M[p] = M[p], M[rk]; inv = iv(M[rk][c])
        M[rk] = [ml(x, inv) for x in M[rk]]
        for i in range(len(M)):
            if i != rk and nz(M[i][c]):
                f = M[i][c]; M[i] = [sb(x, ml(f, y)) for x, y in zip(M[i], M[rk])]
        rk += 1
    return rk
def minv(A):
    n = len(A); M = [A[i][:] + eye(n)[i] for i in range(n)]
    for c in range(n):
        p = next(i for i in range(c, n) if nz(M[i][c])); M[c], M[p] = M[p], M[c]
        inv = iv(M[c][c]); M[c] = [ml(x, inv) for x in M[c]]
        for i in range(n):
            if i != c and nz(M[i][c]):
                f = M[i][c]; M[i] = [sb(x, ml(f, y)) for x, y in zip(M[i], M[c])]
    return [r[n:] for r in M]
def prod(gs, n):
    P = eye(n)
    for g in gs: P = mm(P, g)
    return P
def fixdim(gens, n):
    """dim of the common fixed space of the group generated by gens."""
    if not gens: return n
    rows = []
    for g in gens: rows += msub(g, eye(n))
    return n - rank(rows)

# ---------- the gate on one marking ----------
class Marking:
    def __init__(self, gs, n):
        self.g = gs; self.n = n; self.N = len(gs)
        assert prod(gs, n) == eye(n), "product is not one"
        self._P = {}
    def P(self, i, j):                       # product g_i ... g_j (inclusive, 0-based)
        if (i, j) not in self._P:
            self._P[(i, j)] = self.g[i] if i == j else mm(self.P(i, j - 1), self.g[j])
        return self._P[(i, j)]
    def edge(self, i, j): return fixdim([self.P(i, j)], self.n)
    def vert(self, i, m, j): return fixdim([self.P(i, m), self.P(m + 1, j)], self.n)
    def dp(self):
        """exact max and min of w over all planar trees, rooted at the last leaf; with witnesses."""
        N = self.N
        @lru_cache(maxsize=None)
        def f(i, j):
            if i == j: return (0, 0, None, None)
            best = None
            for m in range(i, j):
                a, b = f(i, m), f(m + 1, j)
                c = (self.edge(i, m) if m > i else 0) + (self.edge(m + 1, j) if j > m + 1 else 0) - self.vert(i, m, j)
                hi, lo = a[0] + b[0] + c, a[1] + b[1] + c
                if best is None:
                    best = [hi, lo, m, m]
                else:
                    if hi > best[0]: best[0], best[2] = hi, m
                    if lo < best[1]: best[1], best[3] = lo, m
            return tuple(best)
        top = f(0, N - 2)
        def nodes(i, j, which):
            if i == j: return []
            m = f(i, j)[2 if which == 'max' else 3]
            return [(i, j)] + nodes(i, m, which) + nodes(m + 1, j, which)
        return top[0], top[1], nodes(0, N - 2, 'max'), nodes(0, N - 2, 'min')

    def evaluate(self, node_intervals):
        """direct evaluation of a planar tree given by its internal-node intervals (0-based, inside [0, N-2])."""
        N = self.N; S = set(node_intervals)
        assert (0, N - 2) in S and len(S) == N - 2, "not a trivalent tree on N leaves"
        w = 0
        for (i, j) in S:
            # children: the maximal proper sub-intervals in S, or leaves
            kids = []; k = i
            while k <= j:
                best = (k, k)
                for (a, b) in S:
                    if a == k and (a, b) != (i, j) and best[1] < b <= j:
                        best = (a, b)
                kids.append(best); k = best[1] + 1
            assert len(kids) == 2, ("not binary", (i, j), kids)
            w -= fixdim([self.P(*kids[0]), self.P(*kids[1])], self.n)
            if (i, j) != (0, N - 2): w += self.edge(i, j)
        return w

def all_planar(i, j):
    if i == j: yield []; return
    for m in range(i, j):
        for L in all_planar(i, m):
            for R in all_planar(m + 1, j):
                yield [(i, j)] + L + R

