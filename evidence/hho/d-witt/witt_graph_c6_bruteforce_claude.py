"""Independent check of the graph-W0 extrema for three C6 tuples (Claude, 16 Nov 2026).

Method differs from the DP of PR #76: every labelled trivalent tree on the ten
branch points is built explicitly by successive leaf insertion into edges
(2,027,025 trees), and for each tree the chi_1-part of H^1 of the dual graph of
the admissible cover is computed from the general Euler formula

    dim W0 = sum_{internal edges e} dim V^{<g_e>} - sum_{vertices v} dim V^{H_v} + dim V^G,

with V = chi_1 (faithful rank one, so dim V^H = 1 iff H = 1, and V^G = 0).
H_v is generated by the three elements at v; g_e is the product on one side of e.
Standard library only.  Usage: python3 -I witt_graph_c6_bruteforce_claude.py
"""
import sys
CASES = {
    "C6 separator (2^5,3,4^3,5), recorded class [2]": [2]*5 + [3] + [4]*3 + [5],
    "C6 (3^8,1,5), recorded class [1]": [3]*8 + [1, 5],
    "C6 (3^8,2,4), recorded class [1]": [3]*8 + [2, 4],
}

def extrema(ex):
    n = len(ex)
    assert sum(ex) % 6 == 0 and all(x % 6 for x in ex)
    # tree: adjacency over nodes; leaves 0..n-1, internal nodes n, n+1, ...
    adj = {0: [n], 1: [n], 2: [n], n: [0, 1, 2]}
    nxt = [n + 1]
    lo, hi, count = 10**9, -10**9, 0

    def evaluate():
        # side sum of every directed edge (u -> v) = sum of leaves on v's side
        # root at leaf 0
        parent = {0: None}; order = [0]
        for u in order:
            for w in adj[u]:
                if w not in parent:
                    parent[w] = u; order.append(w)
        sub = {}
        for u in reversed(order):
            s = ex[u] if u < n else 0
            for w in adj[u]:
                if parent.get(w) == u: s += sub[w]
            sub[u] = s % 6
        e = 0; vtx = 0
        for u in order:
            if u < n: continue
            # internal node: its three incident edges have side sums sub[child], ..., and toward parent
            zs = [sub[w] == 0 for w in adj[u] if parent.get(w) == u]
            zs.append(sub[u] == 0)            # edge to the parent: the complement has sum -sub[u]
            p = parent[u]
            if p is not None and p >= n and sub[u] == 0: e += 1   # internal edge (u, parent) with trivial product
            if all(zs): vtx += 1
        return e - vtx

    def insert(k):
        nonlocal lo, hi, count
        if k == n:
            v = evaluate(); count += 1
            if v < lo: lo = v
            if v > hi: hi = v
            return
        edges = [(u, w) for u in adj for w in adj[u] if u < w]
        for (u, w) in edges:
            m = nxt[0]; nxt[0] += 1
            adj[u].remove(w); adj[w].remove(u)
            adj[u].append(m); adj[w].append(m); adj[m] = [u, w, k]; adj[k] = [m]
            insert(k + 1)
            del adj[k]; del adj[m]; adj[u].remove(m); adj[w].remove(m)
            adj[u].append(w); adj[w].append(u)
            nxt[0] -= 1
    insert(3)
    return lo, hi, count

if __name__ == "__main__":
    for name, ex in CASES.items():
        lo, hi, c = extrema(ex)
        print(f"{name}: {c} labelled trivalent trees; min/max dim W0 = {lo}/{hi}", flush=True)
